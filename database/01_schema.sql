-- Dọn dẹp bảng cũ theo thứ tự ràng buộc khóa ngoại
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'BOOKING_AUDIT_LOGS', 'BOOKING_DETAILS', 'BOOKINGS',
        'SEATS', 'SHOWTIMES', 'VOUCHERS', 'CINEMAS', 'MOVIES', 'USERS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. BẢNG USERS (Người dùng & Quản trị viên)
-- Sử dụng CHAR semantics để hỗ trợ tiếng Việt có dấu AL32UTF8
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    USER_ID         VARCHAR2(50 CHAR) PRIMARY KEY,
    FULL_NAME       VARCHAR2(150 CHAR) NOT NULL,
    EMAIL           VARCHAR2(150 CHAR) NOT NULL UNIQUE,
    PASSWORD_HASH   VARCHAR2(255 CHAR) NOT NULL,
    PHONE           VARCHAR2(30 CHAR),
    AVATAR          VARCHAR2(500 CHAR),
    GENDER          VARCHAR2(30 CHAR) DEFAULT 'Khác',
    CITY            VARCHAR2(150 CHAR) DEFAULT 'TP. Hồ Chí Minh',
    ROLE            VARCHAR2(30 CHAR) DEFAULT 'user' CHECK (ROLE IN ('admin', 'user')),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 2. BẢNG MOVIES (Danh sách phim)
-- ----------------------------------------------------------------------------
CREATE TABLE MOVIES (
    MOVIE_ID        VARCHAR2(50 CHAR) PRIMARY KEY,
    TITLE           VARCHAR2(300 CHAR) NOT NULL,
    IMAGE           VARCHAR2(500 CHAR) NOT NULL,
    IS_HOT          NUMBER(1) DEFAULT 0 CHECK (IS_HOT IN (0, 1)) NOT NULL,
    GENRE           VARCHAR2(300 CHAR) NOT NULL,
    DURATION        VARCHAR2(50 CHAR) NOT NULL,
    RATING          VARCHAR2(30 CHAR) NOT NULL,
    SYNOPSIS        CLOB NOT NULL,
    STATUS          VARCHAR2(50 CHAR) DEFAULT 'now_showing' CHECK (STATUS IN ('now_showing', 'coming_soon')) NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 3. BẢNG CINEMAS (Hệ thống rạp chiếu)
-- ----------------------------------------------------------------------------
CREATE TABLE CINEMAS (
    CINEMA_ID       VARCHAR2(50 CHAR) PRIMARY KEY,
    NAME            VARCHAR2(300 CHAR) NOT NULL,
    ADDRESS         VARCHAR2(500 CHAR) NOT NULL,
    IMAGE           VARCHAR2(500 CHAR) NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 4. BẢNG SHOWTIMES (Suất chiếu phim theo rạp & thời gian)
-- ----------------------------------------------------------------------------
CREATE TABLE SHOWTIMES (
    SHOWTIME_ID     VARCHAR2(100 CHAR) PRIMARY KEY,
    CINEMA_ID       VARCHAR2(50 CHAR) NOT NULL REFERENCES CINEMAS(CINEMA_ID) ON DELETE CASCADE,
    MOVIE_ID        VARCHAR2(50 CHAR) NOT NULL REFERENCES MOVIES(MOVIE_ID) ON DELETE CASCADE,
    START_TIME      VARCHAR2(30 CHAR) NOT NULL,
    SHOW_DATE       DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    STATUS          VARCHAR2(30 CHAR) DEFAULT 'AVAILABLE' CHECK (STATUS IN ('AVAILABLE', 'CANCELLED', 'COMPLETED')) NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_SHOWTIME_SCHEDULE UNIQUE (CINEMA_ID, MOVIE_ID, START_TIME, SHOW_DATE)
);

-- ----------------------------------------------------------------------------
-- 5. BẢNG SEATS (Trạng thái ghế của từng suất chiếu: AVAILABLE, HOLDING, BOOKED)
-- ----------------------------------------------------------------------------
CREATE TABLE SEATS (
    SEAT_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SHOWTIME_ID         VARCHAR2(100 CHAR) NOT NULL REFERENCES SHOWTIMES(SHOWTIME_ID) ON DELETE CASCADE,
    SEAT_CODE           VARCHAR2(20 CHAR) NOT NULL,
    ROW_LETTER          VARCHAR2(5 CHAR) NOT NULL,
    SEAT_NUMBER         NUMBER(3) NOT NULL,
    SEAT_TYPE           VARCHAR2(30 CHAR) DEFAULT 'NORMAL' CHECK (SEAT_TYPE IN ('NORMAL', 'VIP')) NOT NULL,
    PRICE               NUMBER(10) DEFAULT 80000 NOT NULL CHECK (PRICE >= 0),
    STATUS              VARCHAR2(30 CHAR) DEFAULT 'AVAILABLE' CHECK (STATUS IN ('AVAILABLE', 'HOLDING', 'BOOKED')) NOT NULL,
    HELD_BY_USER_ID     VARCHAR2(50 CHAR),
    HOLD_EXPIRES_AT     TIMESTAMP,
    UPDATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_SHOWTIME_SEAT UNIQUE (SHOWTIME_ID, SEAT_CODE)
);

-- ----------------------------------------------------------------------------
-- 6. BẢNG VOUCHERS (Mã giảm giá khuyến mãi)
-- ----------------------------------------------------------------------------
CREATE TABLE VOUCHERS (
    VOUCHER_ID      VARCHAR2(50 CHAR) PRIMARY KEY,
    CODE            VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    DISCOUNT_AMOUNT NUMBER(10) NOT NULL CHECK (DISCOUNT_AMOUNT > 0),
    MIN_PRICE       NUMBER(10) DEFAULT 0 NOT NULL CHECK (MIN_PRICE >= 0),
    IS_ACTIVE       NUMBER(1) DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1)) NOT NULL,
    EXPIRY_DATE     TIMESTAMP,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 7. BẢNG BOOKINGS (Hóa đơn đặt vé)
-- ----------------------------------------------------------------------------
CREATE TABLE BOOKINGS (
    BOOKING_ID      VARCHAR2(50 CHAR) PRIMARY KEY,
    USER_ID         VARCHAR2(50 CHAR) NOT NULL REFERENCES USERS(USER_ID),
    SHOWTIME_ID     VARCHAR2(100 CHAR) NOT NULL REFERENCES SHOWTIMES(SHOWTIME_ID),
    MOVIE_TITLE     VARCHAR2(300 CHAR) NOT NULL,
    MOVIE_POSTER    VARCHAR2(500 CHAR),
    CINEMA_NAME     VARCHAR2(300 CHAR) NOT NULL,
    SHOWTIME_TIME   VARCHAR2(50 CHAR) NOT NULL,
    SEATS_STRING    VARCHAR2(300 CHAR) NOT NULL,
    SUBTOTAL_PRICE  NUMBER(12) NOT NULL CHECK (SUBTOTAL_PRICE >= 0),
    DISCOUNT_AMOUNT NUMBER(12) DEFAULT 0 NOT NULL CHECK (DISCOUNT_AMOUNT >= 0),
    TOTAL_PRICE     NUMBER(12) NOT NULL CHECK (TOTAL_PRICE >= 0),
    VOUCHER_CODE    VARCHAR2(50 CHAR),
    STATUS          VARCHAR2(30 CHAR) DEFAULT 'SUCCESS' CHECK (STATUS IN ('SUCCESS', 'PENDING', 'CANCELLED')) NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 8. BẢNG BOOKING_DETAILS (Chi tiết vé từng ghế trong đơn)
-- ----------------------------------------------------------------------------
CREATE TABLE BOOKING_DETAILS (
    DETAIL_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BOOKING_ID      VARCHAR2(50 CHAR) NOT NULL REFERENCES BOOKINGS(BOOKING_ID) ON DELETE CASCADE,
    SEAT_CODE       VARCHAR2(20 CHAR) NOT NULL,
    SEAT_TYPE       VARCHAR2(30 CHAR) NOT NULL,
    PRICE           NUMBER(10) NOT NULL CHECK (PRICE >= 0)
);

-- ----------------------------------------------------------------------------
-- 9. BẢNG BOOKING_AUDIT_LOGS (Ghi vết kiểm toán biến động đặt vé và trạng thái ghế)
-- ----------------------------------------------------------------------------
CREATE TABLE BOOKING_AUDIT_LOGS (
    LOG_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTION          VARCHAR2(50 CHAR) NOT NULL,
    BOOKING_ID      VARCHAR2(50 CHAR),
    SHOWTIME_ID     VARCHAR2(100 CHAR),
    SEAT_CODE       VARCHAR2(50 CHAR),
    USER_ID         VARCHAR2(50 CHAR),
    DESCRIPTION     VARCHAR2(500 CHAR),
    LOG_TIME        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- TẠO CÁC CHỈ MỤC TỐI ƯU HÓA TRUY VẤN (INDEXES)
-- ----------------------------------------------------------------------------
CREATE INDEX IDX_USERS_EMAIL ON USERS(EMAIL);
CREATE INDEX IDX_SHOWTIMES_LOOKUP ON SHOWTIMES(CINEMA_ID, MOVIE_ID, START_TIME);
CREATE INDEX IDX_SEATS_SHOWTIME_STATUS ON SEATS(SHOWTIME_ID, STATUS);
CREATE INDEX IDX_BOOKINGS_USER ON BOOKINGS(USER_ID, CREATED_AT DESC);
CREATE INDEX IDX_BOOKINGS_CREATED ON BOOKINGS(CREATED_AT DESC);
CREATE INDEX IDX_VOUCHERS_CODE_ACTIVE ON VOUCHERS(CODE, IS_ACTIVE);
CREATE INDEX IDX_AUDIT_LOG_TIME ON BOOKING_AUDIT_LOGS(LOG_TIME DESC);

COMMIT;
